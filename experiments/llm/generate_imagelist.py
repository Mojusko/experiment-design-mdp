# Define the expected filename pattern
FILENAME_PATTERN = re.compile(r"^alg-([a-zA-Z0-9]+)_episode_(\d+)_timestep_(\d+)\.png$", re.IGNORECASE)
LAMBDA_DIR_PATTERN = re.compile(r"^lambda[-_]?(.+)$", re.IGNORECASE)


def collect_lambda_directories(image_root):
    """Collect PNGs grouped by lambda directory inside image_root."""
    if not os.path.isdir(image_root):
        print(f"Error: Image directory '{image_root}' not found.")
        return {}

    base_folder = os.path.basename(os.path.normpath(image_root))
    lambda_to_images = {}

    for entry in sorted(os.listdir(image_root)):
        entry_path = os.path.join(image_root, entry)
        if not os.path.isdir(entry_path):
            continue

        lambda_match = LAMBDA_DIR_PATTERN.match(entry)
        if not lambda_match:
            continue

        lambda_key = lambda_match.group(1).replace("_", ".")
        print(f"Scanning directory for lambda={lambda_key}: {entry_path}")

        images = []
        skipped = 0
        for filename in os.listdir(entry_path):
            if FILENAME_PATTERN.match(filename):
                relative_path = os.path.join(base_folder, entry, filename)
                images.append(relative_path.replace(os.sep, "/"))
            elif filename.lower().endswith(".png"):
                skipped += 1

        if images:
            lambda_to_images[lambda_key] = natsort.natsorted(images)
            print(f"  Found {len(images)} images matching pattern.")
        else:
            print("  Warning: No matching images found in this directory.")

        if skipped:
            print(f"  Skipped {skipped} PNG files that did not match the expected pattern (alg-*_episode_*_timestep_*.png).")

    return dict(sorted(lambda_to_images.items(), key=lambda item: float(item[0]) if item[0].replace('.', '', 1).isdigit() else item[0]))


def generate_js_file(images_by_lambda, output_path, default_lambda):
    """Generates the JavaScript file with grouped image lists."""
    # Format as a JavaScript object assignment with deterministic ordering
    js_content = "// Generated by generate_imagelist.py\n"
    js_content += f"const imageFilesByLambda = {json.dumps(images_by_lambda, indent=4)};\n"
    js_content += f"const defaultLambdaKey = {json.dumps(default_lambda)};\n"
    js_content += "const urlParams = new URLSearchParams(window.location.search);\n"
    js_content += "let requestedLambdaParam = urlParams.get('lam') || urlParams.get('lambda') || defaultLambdaKey;\n"
    js_content += "if (!Object.prototype.hasOwnProperty.call(imageFilesByLambda, requestedLambdaParam)) {\n"
    js_content += "    if (requestedLambdaParam !== defaultLambdaKey) {\n"
    js_content += "        console.warn(`Unknown lambda value '${requestedLambdaParam}' requested in URL. Falling back to default ${defaultLambdaKey}.`);\n"
    js_content += "    }\n"
    js_content += "    requestedLambdaParam = defaultLambdaKey;\n"
    js_content += "}\n"
    js_content += "if (!urlParams.has('lam') || urlParams.get('lam') !== requestedLambdaParam || urlParams.has('lambda')) {\n"
    js_content += "    urlParams.set('lam', requestedLambdaParam);\n"
    js_content += "    if (urlParams.has('lambda')) {\n"
    js_content += "        urlParams.delete('lambda');\n"
    js_content += "    }\n"
    js_content += "    const newUrl = `${window.location.pathname}?${urlParams.toString()}${window.location.hash}`;\n"
    js_content += "    window.history.replaceState(null, '', newUrl);\n"
    js_content += "}\n"
    js_content += "const imageFiles = imageFilesByLambda[requestedLambdaParam] || [];\n"
    js_content += "const activeLambda = requestedLambdaParam;\n"
    js_content += "window.selectedLambda = activeLambda;\n"
    js_content += "window.imageFilesByLambda = imageFilesByLambda;\n"
    js_content += "window.imageFiles = imageFiles;\n"
    js_content += "window.defaultLambdaKey = defaultLambdaKey;\n"
    js_content += "try {\n"
    js_content += "    localStorage.setItem('currentLambda', activeLambda);\n"
    js_content += "} catch (err) {\n"
    js_content += "    console.warn('Unable to persist lambda selection in localStorage:', err);\n"
    js_content += "}\n"

    try:
        os.makedirs(os.path.dirname(output_path), exist_ok=True)
        with open(output_path, "w") as f:
            f.write(js_content)
        total_images = sum(len(v) for v in images_by_lambda.values())
        print(f"Successfully generated {output_path} with {total_images} images across {len(images_by_lambda)} lambda groups.")
    except Exception as e:
        print(f"Error writing to {output_path}: {e}")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Generate a JavaScript image list from PNG files in a directory.")
    parser.add_argument(
        "-d", "--directory",
        required=True,
        help="Directory containing lambda-specific subdirectories of grid images (.png files)."
    )
    parser.add_argument(
        "-o", "--output-file", # Changed argument name to reflect it's a file path
        required=True,
        # Updated help text
        help="Full path to the output JavaScript file (e.g., experiments/llm/experiment_html/js/imageList.js)."
    )
    parser.add_argument(
        "--default-lambda",
        default="0.1",
        help="Default lambda value to fall back to when the URL does not specify a known lambda." 
    )
    args = parser.parse_args()

    image_dir = args.directory
    output_js_file = args.output_file

    print(f"Scanning for images in: {os.path.abspath(image_dir)}")
    print(f"Output JS file will be: {os.path.abspath(output_js_file)}") # Added confirmation message
    images_by_lambda = collect_lambda_directories(image_dir)

    if not images_by_lambda:
        print("No images found. JS file not generated.")
        raise SystemExit(1)

    default_lambda = args.default_lambda
    if default_lambda not in images_by_lambda:
        first_key = next(iter(images_by_lambda))
        print(f"Warning: Default lambda '{default_lambda}' not present. Falling back to '{first_key}'.")
        default_lambda = first_key

    generate_js_file(images_by_lambda, output_js_file, default_lambda)
